const uint8_t *plato_c64_get_screen_glyph_8x8(uint8_t screen_code, int bank) {
    size_t offset = (bank == C64_FONT_BANK_LOWER_UPPER ? 2048 : 0) + ((size_t)screen_code * 8);
    if (offset + 8 > sizeof(c64_rom)) return &c64_rom[2048 + 32 * 8]; /* fallback space */
    return &c64_rom[offset];
}

uint8_t plato_c64_ascii_to_screen_code(uint8_t c) {
    if (c < 32) return 32; /* space */
    if (c == 32) return 32;
    if (c >= 33 && c <= 63) return c; /* numbers and standard punctuation */
    if (c == 64) return 0;  /* @ */
    if (c >= 65 && c <= 90) return c; /* Uppercase A-Z in Bank 1 */
    if (c == 91) return 27; /* [ */
    if (c == 92) return 92; /* \ */
    if (c == 93) return 29; /* ] */
    if (c == 94) return 30; /* ^ */
    if (c == 95) return 64; /* _ (horizontal line) */
    if (c == 96) return 39; /* ` -> apostrophe */
    if (c >= 97 && c <= 122) return (uint8_t)(c - 96); /* Lowercase a-z -> 1..26 in Bank 1 */
    if (c == 123) return 27; /* { -> [ */
    if (c == 124) return 93; /* | -> vertical bar */
    if (c == 125) return 29; /* } -> ] */
    if (c == 126) return 30; /* ~ -> ^ */
    return 32;
}

static uint8_t s_ascii_glyphs_8x16[128][16];
static bool s_glyphs_initialized = false;

static void init_ascii_glyphs_if_needed(void) {
    if (s_glyphs_initialized) return;
    for (int ch = 0; ch < 128; ch++) {
        uint8_t sc = plato_c64_ascii_to_screen_code((uint8_t)ch);
        const uint8_t *raw = plato_c64_get_screen_glyph_8x8(sc, C64_FONT_BANK_LOWER_UPPER);
        /* Centratura verticale dell'8x8 autentico C64 all'interno della cella 8x16 */
        for (int r = 0; r < 16; r++) s_ascii_glyphs_8x16[ch][r] = 0;
        for (int r = 0; r < 8; r++) {
            s_ascii_glyphs_8x16[ch][r + 4] = raw[r];
        }
    }
    s_glyphs_initialized = true;
}

const uint8_t *plato_c64_get_ascii_glyph_8x16(uint8_t ascii_ch) {
    init_ascii_glyphs_if_needed();
    if (ascii_ch >= 128) return s_ascii_glyphs_8x16[32];
    return s_ascii_glyphs_8x16[ascii_ch];
}

void plato_c64_load_font_m0(plato_font_t *font) {
    if (!font) return;
    init_ascii_glyphs_if_needed();
    memcpy(font->m0, s_ascii_glyphs_8x16, sizeof(font->m0));
}
